"""Governance baseline — the cross-cutting component eval EVERY agent inherits.

Encodes CLAUDE.md's non-negotiable output rules so each agent doesn't re-declare
them: evidence tracing, assumptions documented, provenance, and (when the input
is available) faithfulness with no invented data. Per-agent suites call this and
then add their own specifics; the runtime layer calls it on live agent output.

evaluate(target, context=None):
  target  = the agent's output (path or text)
  context = the agent's INPUT (path or text), if available. When present, the
            faithfulness judge grounds claims against it; when absent it's skipped.
"""
from __future__ import annotations

import re
from pathlib import Path

from rubrics.base import CheckResult

_EVIDENCE = re.compile(r"\bE\d{2,}\b|\bCAP-[A-Z0-9-]+\b|source\s*:|benchmark", re.I)
_ASSUMPTION = re.compile(r"assumption", re.I)
_CONFIDENCE = re.compile(r"confidence|\b(high|medium|low)\b", re.I)
_PROVENANCE = re.compile(r"generated by|provenance|agent\s*:|\b\d{4}-\d{2}-\d{2}\b", re.I)


def _read(x: str) -> str:
    try:
        p = Path(x)
        return p.read_text(errors="replace") if p.exists() else x
    except (OSError, ValueError):
        return x


def evaluate(target: str, context: str | None = None) -> list[CheckResult]:
    text = _read(target)
    checks: list[CheckResult] = []

    ev = len(_EVIDENCE.findall(text))
    checks.append(CheckResult("gov_evidence_traced", 1.0 if ev >= 3 else ev / 3.0, ev >= 3,
                              detail=f"{ev} evidence/source references"))

    has_assump = bool(_ASSUMPTION.search(text))
    has_conf = bool(_CONFIDENCE.search(text))
    checks.append(CheckResult("gov_assumptions_documented",
                              1.0 if (has_assump and has_conf) else (0.5 if has_assump else 0.0),
                              has_assump,
                              detail=f"assumptions={'yes' if has_assump else 'no'}, confidence-labelled={'yes' if has_conf else 'no'}"))

    prov = bool(_PROVENANCE.search(text))
    checks.append(CheckResult("gov_provenance_present", 1.0 if prov else 0.5, prov,
                              detail="provenance/date stamp present" if prov else "no provenance marker"))

    # Faithfulness judge — only meaningful when we have the input to ground against.
    from rubrics.judge.judge import judge
    if context is not None:
        ctx = _read(context)
        checks.append(judge("faithful_no_invention", f"INPUT:\n{ctx[:25000]}\n\nOUTPUT:\n{text[:25000]}",
                            snapshot=None, threshold=0.8))
    else:
        checks.append(CheckResult("judge:faithful_no_invention", 0.0, True, skipped=True,
                                  detail="no input context — faithfulness skipped (runs at runtime / with golden input)"))
    return checks
